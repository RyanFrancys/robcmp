void return_and_sleep(int  result) {
    volatile int a=result;
    // As part of the AVR GCC calling convention,
    // result argument (first arg) is passed in r24 and r25
    // disable interruptions and sleep; this is used to quit simavr in our tests
    asm("cli");
    asm("sleep");
}

int main()
{
    float i = 0.0;
    int pos = 0;
    const int entries = sizeof(values)/sizeof(float);
    #define casas_decimais 1E-5
    while (pos < entries)
    {

        float aux = Sqrt(i);
        float valor = values[pos];
        if (fabs(aux - valor) > casas_decimais)
        {
            if (i != 0)
            {
                return_and_sleep(pos);
                return pos;
            }
            else
            {
                return_and_sleep(1);
                return 1;
            }
        }
        i = i + 0.5;
        pos++;
    }
    return_and_sleep(0);
    return 0;
}
